using System.Globalization;
using System.Text;
using DXMirror.Core.Settings;

namespace DXMirror.Core.Receiver;

/// <summary>Paths that the receiver needs at runtime (all resolved by the host application).</summary>
public sealed record ReceiverPaths(
    string KeyFile,
    string StartupFile);

/// <summary>
/// Translates <see cref="AppSettings"/> into a UxPlay 1.74 startup file ("-rc" file).
/// Options are written to a UTF-8 file instead of the command line because Windows passes
/// command-line arguments to MinGW programs in the ANSI code page, and UxPlay rejects
/// non-UTF-8 arguments (e.g. a device name containing "–" or umlauts).
///
/// Only options documented in "uxplay -h" (v1.74) are used.
/// </summary>
public static class UxPlayStartupFile
{
    public static IReadOnlyList<string> BuildOptionLines(AppSettings s, ReceiverPaths paths, UxPlayCapabilities caps)
    {
        ArgumentNullException.ThrowIfNull(s);
        var lines = new List<string>();
        void Add(string option, params string[] values)
        {
            if (!caps.Supports(option)) return;
            var sb = new StringBuilder(option);
            foreach (var v in values) sb.Append(' ').Append(Quote(v));
            lines.Add(sb.ToString());
        }

        // Name exactly as configured (no "@hostname" suffix).
        Add("n", s.DeviceName);
        Add("nh");

        // Persistent server key => the iPhone keeps recognising this PC across restarts.
        Add("key", paths.KeyFile);

        // ---- video ----
        if (s.AudioOnlyMode)
        {
            Add("vs", "0");
        }
        else
        {
            Add("s", string.Create(CultureInfo.InvariantCulture, $"{s.MaxWidth}x{s.MaxHeight}@{s.MaxFps}"));
            Add("fps", s.MaxFps.ToString(CultureInfo.InvariantCulture));
            if (!s.HardwareAcceleration) Add("avdec");
            var sink = s.VideoRenderer == "d3d12" ? "d3d12videosink" : "d3d11videosink";
            var sinkOptions = s.Scaling == "stretch" ? " force-aspect-ratio=false" : "";
            Add("vs", sink + sinkOptions);
            if (s.EnableH265) Add("h265");
            // keep the window when the iPhone stops mirroring is handled by DXMirror, so close it
            Add("nofreeze");
        }

        // ---- audio ----
        var audioSink = new StringBuilder("wasapisink");
        if (s.AudioOutputDeviceId is { } dev && AudioDeviceIdRules.IsValid(dev))
            audioSink.Append(" device=\"").Append(dev).Append('"');
        if (s.WasapiLowLatency) audioSink.Append(" low-latency=true");
        Add("as", audioSink.ToString());
        Add("al", (s.AudioLatencyMs / 1000.0).ToString("0.000", CultureInfo.InvariantCulture));
        if (!s.AudioOnlyMode)
        {
            if (s.AvSyncEnabled)
            {
                if (s.AvSyncOffsetMs != 0) Add("vsync", s.AvSyncOffsetMs.ToString(CultureInfo.InvariantCulture));
                else Add("vsync");
            }
            else
            {
                Add("vsync", "no");
            }
        }

        // ---- connection ----
        Add("reset", s.ConnectionTimeoutSeconds.ToString(CultureInfo.InvariantCulture));
        if (s.NewClientTakesOver) Add("nohold");

        // ---- diagnostics ----
        if (s.DebugMode || s.LogLevel == "debug")
        {
            Add("d", "1");
            Add("FPSdata"); // client-side streaming reports, very verbose
        }

        return lines;
    }

    public static string BuildFileContent(IEnumerable<string> lines)
    {
        var sb = new StringBuilder();
        sb.Append("# Generated by DXMirror – do not edit, changes are overwritten on every start\n");
        foreach (var l in lines) sb.Append(l).Append('\n');
        return sb.ToString();
    }

    /// <summary>
    /// Quotes a value for UxPlay's startup-file tokenizer: items are separated by spaces and may be
    /// enclosed in single or double quotes. A quote character closes the item only when followed by a
    /// space or end of line, so we pick the quote type that does not occur in the value.
    /// </summary>
    public static string Quote(string value)
    {
        if (value.Length > 0 && !value.Contains(' ') && !value.Contains('"') && !value.Contains('\'') && !value.StartsWith('#'))
            return value;
        if (!value.Contains('\'')) return "'" + value + "'";
        if (!value.Contains('"')) return "\"" + value + "\"";
        // both quote types present: drop single quotes (device names are sanitised, so this is a last resort)
        return "\"" + value.Replace("\"", "", StringComparison.Ordinal) + "\"";
    }
}

public static class AudioDeviceIdRules
{
    /// <summary>Windows MMDevice endpoint ids look like "{0.0.0.00000000}.{xxxxxxxx-xxxx-...}".</summary>
    public static bool IsValid(string id) =>
        id.Length is > 10 and < 128 && id.All(c => char.IsAsciiHexDigit(c) || c is '{' or '}' or '.' or '-');
}
